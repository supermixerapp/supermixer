import { describe, expect, it } from 'vitest'

import { addColumn, countRows, createTable, deleteRows, insertRow, selectRows, typeSql, updateRow } from './table-sql'

describe('row SQL', () => {
  it('selects with filters, sorts and paging, values as parameters', () => {
    const q = selectRows('public', 'My Table', {
      filters: [
        { column: 'name', op: 'ilike', value: "%o'brien%" },
        { column: 'age', op: 'gte', value: '18' },
        { column: 'deleted_at', op: 'is_null', value: '' },
        { column: 'status', op: 'in', value: 'a, b' },
      ],
      sorts: [{ column: 'created_at', direction: 'desc' }],
      limit: 100,
      offset: 200,
    })
    expect(q.sql).toBe(
      'select * from "public"."My Table" where "name"::text ilike $1 and "age" >= $2 and "deleted_at" is null and "status"::text in ($3, $4) order by "created_at" desc limit 100 offset 200'
    )
    expect(q.params).toEqual(["%o'brien%", '18', 'a', 'b'])
  })

  it('counts with the same filters', () => {
    expect(countRows('s', 't', [{ column: 'x', op: 'eq', value: '1' }])).toEqual({
      sql: 'select count(*)::text as count from "s"."t" where "x" = $1',
      params: ['1'],
    })
  })

  it('updates, inserts and deletes by primary key', () => {
    expect(updateRow('public', 't', { title: 'x', done: null }, { id: '7' })).toEqual({
      sql: 'update "public"."t" set "title" = $1, "done" = $2 where "id" is not distinct from $3',
      params: ['x', null, '7'],
    })
    expect(insertRow('public', 't', { title: 'a"b' })).toEqual({
      sql: 'insert into "public"."t" ("title") values ($1)',
      params: ['a"b'],
    })
    expect(insertRow('public', 't', {}).sql).toBe('insert into "public"."t" default values')
    expect(deleteRows('public', 't', [{ a: '1', b: '2' }, { a: '3', b: null }])).toEqual({
      sql: 'delete from "public"."t" where ("a" is not distinct from $1 and "b" is not distinct from $2) or ("a" is not distinct from $3 and "b" is not distinct from $4)',
      params: ['1', '2', '3', null],
    })
    expect(deleteRows('public', 't', []).sql).toBe('delete from "public"."t" where false')
  })

  it('quotes hostile identifiers', () => {
    expect(selectRows('public', 'x"; drop table y; --', { filters: [], sorts: [], limit: 1, offset: 0 }).sql).toBe(
      'select * from "public"."x""; drop table y; --" limit 1 offset 0'
    )
  })
})

describe('schema SQL', () => {
  it('creates a table with RLS, a foreign key and comments', () => {
    const sql = createTable(
      'public',
      'todos',
      [
        { name: 'id', type: 'int8', nullable: false, primary: true, identity: true },
        { name: 'created_at', type: 'timestamptz', nullable: false, default: 'now()' },
        { name: 'user_id', type: 'uuid', nullable: true, references: { schema: 'auth', table: 'users', column: 'id', onDelete: 'cascade' } },
        { name: 'tags', type: 'text', isArray: true, nullable: true, comment: "it's a list" },
      ],
      { rls: true, comment: 'Things to do' }
    )
    expect(sql).toBe(`create table "public"."todos" (
  "id" int8 generated by default as identity primary key,
  "created_at" timestamptz not null default now(),
  "user_id" uuid references "auth"."users" ("id") on delete cascade,
  "tags" text[]
);
alter table "public"."todos" enable row level security;
comment on column "public"."todos"."tags" is 'it''s a list';
comment on table "public"."todos" is 'Things to do';`)
  })

  it('adds a column with an enum type', () => {
    expect(addColumn('public', 't', { name: 'status', type: 'public.Mood', nullable: false, default: "'ok'" })).toBe(
      `alter table "public"."t" add column "status" "public"."Mood" not null default 'ok';`
    )
  })

  it('keeps built-in types bare and quotes anything else', () => {
    expect(typeSql('varchar(255)')).toBe('varchar(255)')
    expect(typeSql('timestamp with time zone')).toBe('timestamp with time zone')
    expect(typeSql('Weird;type')).toBe('"Weird;type"')
  })
})
