// Writes src/lib/i18n/resources.gen.d.ts: i18next's types for the English
// catalogs, so t('ns:key') only accepts keys that exist. Run it (pnpm
// generate:i18n) after adding or removing a namespace file; locales.test.ts
// fails if it's out of date.
import { readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const dir = fileURLToPath(new URL('../src/locales/en/', import.meta.url))
const namespaces = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -'.json'.length))
  .sort()

const ident = (ns) => ns.replace(/[^A-Za-z0-9]+(.)/g, (_, c) => c.toUpperCase())
const out = `// Generated by scripts/gen-i18n-types.mjs from src/locales/en; don't edit.
${namespaces.map((ns) => `import type ${ident(ns)} from '../../locales/en/${ns}.json'`).join('\n')}

export type Namespace = ${namespaces.map((ns) => JSON.stringify(ns)).join(' | ')}

declare module 'i18next' {
  interface CustomTypeOptions {
    defaultNS: 'common'
    resources: {
${namespaces.map((ns) => `      ${JSON.stringify(ns)}: typeof ${ident(ns)}`).join('\n')}
    }
  }
}
`
writeFileSync(fileURLToPath(new URL('../src/lib/i18n/resources.gen.d.ts', import.meta.url)), out)
console.log(`i18n: types for ${namespaces.length} namespaces`)
