set -euo pipefail

export PGHOST="$PGHOST"
export PGPORT="$PGPORT"
export PGUSER="$PGUSER"
export PGPASSWORD="$PGPASSWORD"
export PGDATABASE="$PGDATABASE"

# Explanation of pg_dumpall flags:
#
#   --roles-only     only include create, alter, and grant role statements
#
# Explanation of sed substitutions:
#
#   - do not emit psql meta commands
#   - do not create or alter reserved roles as they are blocked by supautils
#   - explicitly allow altering safe attributes, ie. statement_timeout, pgrst.*
#   - discard role attributes that require superuser, ie. nosuperuser, noreplication
#   - do not alter membership grants by supabase_admin role
#   - do not grant parameter privileges to reserved roles outside quoted SQL
pg_dumpall \
    --roles-only \
    --role "postgres" \
    --quote-all-identifier \
    --no-role-passwords \
    --no-comments \
| LC_ALL=C awk -v reserved_roles="$RESERVED_ROLES" '
# Parenthesized field references survive the CLI dry-run expander.
BEGIN { single_quote = sprintf("%c", 39) }
{
    line = $(0)
    if (quote == "" && line ~ ("^GRANT [A-Z ,]+ ON PARAMETER \".*\" TO \"(" reserved_roles ")\"([ ;]|$)"))
        $(0) = "-- " line
    print
    count = length(line)
    end = 0
    for (i = 1; i <= count; i++) {
        if (i > end) {
            chunk = substr(line, i, 1025)
            start = i
            end = i + 1023
        }
        char = substr(chunk, i - start + 1, 1)
        next_char = substr(chunk, i - start + 2, 1)
        if (quote != "") {
            if (char == quote) {
                if (next_char == quote) i++
                else quote = ""
            }
        } else if (char == single_quote || char == "\"") quote = char
        else if (char == "-" && next_char == "-") break
    }
}' \
| sed -E 's/^\\(un)?restrict .*$/-- &/' \
| sed -E "s/^CREATE ROLE \"($RESERVED_ROLES)\"/-- &/" \
| sed -E "s/^ALTER ROLE \"($RESERVED_ROLES)\"/-- &/" \
| sed -E "s/ (NOSUPERUSER|NOREPLICATION)//g" \
| sed -E "s/^-- (.* SET \"($ALLOWED_CONFIGS)\" .*)/\1/" \
| sed -E "s/GRANT \".*\" TO \"($RESERVED_ROLES)\"/-- &/" \
| sed -E "${EXTRA_SED:-}" \
| uniq

# Reset session config generated by pg_dump
echo "RESET ALL;"
